/**
 * Reconciles any input district name against the canonical 36 Maharashtra districts.
 */
export function resolveCanonicalDistrict(inputName: string): DistrictInfo | undefined {
  if (!inputName) return undefined;
  const clean = inputName.trim().toLowerCase().replace(/[^a-z0-9]/g, '');
  return MAHARASHTRA_DISTRICTS.find(d => {
    if (d.name.toLowerCase().replace(/[^a-z0-9]/g, '') === clean) return true;
    if (d.id.replace(/[^a-z0-9]/g, '') === clean) return true;
    return d.aliases.some(alias => alias.toLowerCase().replace(/[^a-z0-9]/g, '') === clean);
  });
}

